import { Hono } from "hono";
import { z } from "zod";
import type { MarketConfig } from "../db/market-actions.js";
import { OfferRow, loadListingRow } from "../db/market.js";
import { ApiError } from "../lib/errors.js";
import { broadcast } from "../lib/realtime.js";
import { one } from "../lib/respond.js";
import { adminClient } from "../lib/supabase.js";
import { parseBody } from "../lib/validate.js";
import { requireUser, type AuthEnv, type TokenVerifier } from "../middleware/auth.js";
import { Cents } from "../schemas/common.js";
import { negotiate, sellerFloor } from "../services/bargain.js";
import { hasOpenOffer, offerOut, placeOffer } from "./offers.js";

// Auto-bargain (module 10). The negotiation runs to the end inside the request, so a session is never left
// `negotiating`; a deal becomes a normal pending offer (auto_generated) that the seller still taps to accept.

export const AutoBargainReq = z.object({
  max_price_cents: Cents.refine((v) => v > 0, "Must be above $0"),
  style: z.enum(["quick", "balanced", "patient"]).default("balanced"),
});

const Round = z.object({ by: z.enum(["buyer_agent", "seller_agent"]), amount_cents: z.number().int(), at: z.string() });
const SessionRow = z.object({
  id: z.guid(), school_id: z.guid(), buyer_id: z.guid(), status: z.enum(["negotiating", "deal_found", "no_deal"]),
  rounds: z.array(Round), offer_id: z.guid().nullable(),
});

const check = <T>(r: { data: T | null; error: unknown }): T => {
  if (r.error) throw r.error;
  return r.data as T;
};

const guid = (raw: string, what: string) => {
  const id = z.guid().safeParse(raw);
  if (!id.success) throw new ApiError(404, "NOT_FOUND", `${what} not found`);
  return id.data;
};

async function proposedOffer(offerId: string | null, schoolId: string) {
  if (!offerId) return null;
  const data = check(await adminClient().from("offers").select("*").eq("id", offerId).eq("school_id", schoolId).maybeSingle());
  return data ? offerOut(OfferRow.parse(data)) : null;
}

export const bargainRoutes = (verify: TokenVerifier, cfg: MarketConfig) => new Hono<AuthEnv>()
  .use("/listings/:id/auto-bargain", requireUser(verify))
  .use("/auto-bargain/*", requireUser(verify))

  .post("/listings/:id/auto-bargain", async (c) => {
    const body = await parseBody(c, AutoBargainReq);
    const { id: buyerId, schoolId } = c.var.user;
    const listing = await loadListingRow(guid(c.req.param("id"), "Listing"), schoolId);
    if (listing.status === "draft" || listing.status === "removed") throw new ApiError(404, "NOT_FOUND", "Listing not found");
    if (listing.status !== "active") throw new ApiError(409, "INVALID_STATE", "Listing isn't available");
    if (listing.seller_id === buyerId) throw new ApiError(403, "FORBIDDEN", "You can't bargain on your own listing");
    if (await hasOpenOffer(listing.id, buyerId)) throw new ApiError(409, "INVALID_STATE", "You already have an open offer on this listing");

    const result = negotiate({ askCents: listing.price_cents, floorCents: sellerFloor(listing), maxCents: body.max_price_cents, style: body.style });
    const at = new Date().toISOString();
    const rounds = result.rounds.map((r) => ({ ...r, at }));
    const fulfillment = listing.fulfillment.includes("in_person") ? "in_person" : listing.fulfillment[0];
    if (result.priceCents !== null && !fulfillment) throw new ApiError(409, "INVALID_STATE", "Listing has no way to hand it over");

    const offer = result.priceCents !== null && fulfillment
      ? (await placeOffer({
        listing, buyerId, amountCents: result.priceCents, fulfillment, cfg, autoGenerated: true,
        message: `Auto-bargained in ${result.rounds.length} rounds`,
      })).row
      : null;
    const session = SessionRow.parse(check(await adminClient().from("bargain_sessions").insert({
      school_id: schoolId, listing_id: listing.id, buyer_id: buyerId, max_price_cents: body.max_price_cents, style: body.style,
      status: result.status, rounds, offer_id: offer?.id ?? null,
    }).select("id, school_id, buyer_id, status, rounds, offer_id").single()));

    const proposed = offer ? await offerOut(offer) : null;
    await broadcast(`auto-bargain:${session.id}`, "finished", { status: session.status, proposed_offer: proposed });
    return c.json(one({ session_id: session.id, status: session.status }), 201);
  })

  .get("/auto-bargain/:id", async (c) => {
    const { id: userId, schoolId } = c.var.user;
    const id = guid(c.req.param("id"), "Session");
    const data = check(await adminClient().from("bargain_sessions").select("id, school_id, buyer_id, status, rounds, offer_id")
      .eq("id", id).eq("school_id", schoolId).maybeSingle());
    const session = data ? SessionRow.parse(data) : null;
    if (!session || session.buyer_id !== userId) throw new ApiError(404, "NOT_FOUND", "Session not found");
    return c.json(one({
      status: session.status,
      rounds: session.rounds.map((r) => ({ ...r, at: new Date(r.at).toISOString() })),
      proposed_offer: await proposedOffer(session.offer_id, schoolId),
    }));
  });
